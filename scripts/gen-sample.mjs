// Bundles seed/*.csv into src/lib/sample-data.ts so sample data works on serverless hosts without file access.
import fs from "node:fs";

const files = {
  sku: "sku_master.csv",
  distributor: "distributor_master.csv",
  sales: "weekly_sales.csv",
  inventory: "current_inventory.csv",
  calendar: "calendar.csv",
};
const out = {};
for (const [k, f] of Object.entries(files)) out[k] = fs.readFileSync(`seed/${f}`, "utf8").replace(/\r\n/g, "\n");
fs.writeFileSync(
  "src/lib/sample-data.ts",
  `// Generated by scripts/gen-sample.mjs from seed/*.csv. Do not edit by hand.\nexport const SAMPLE_FILES: Record<"sku" | "distributor" | "sales" | "inventory" | "calendar", string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log("wrote src/lib/sample-data.ts");
